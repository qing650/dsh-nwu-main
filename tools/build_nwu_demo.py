def source_lines(*keys: str) -> str:
    """把来源键渲染成 markdown 来源小节。"""
    out = ["\n\n## 来源"]
    for key in keys:
        url = SRC["url_jwc"] if key == "jwc_home" else SRC[f"url_{key}"]
        label = SRC[key]
        out.append(f"- [{label}]({url})")
    return "\n".join(out)


