def build(config: dict) -> None:
    site = config["site"]
    kinds = config["kinds"]
    qa = config.get("qa", {})
    office = config.get("office", {})
    data_dir = ROOT / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    # 顺序：索引在前，其余按配置 kinds 顺序与节点定义顺序稳定排列
    ordered = sorted(
        NODES,
        key=lambda n: (0 if n["k"] == "索引" else 1, kinds["order"].index(n["k"]) if n["k"] in kinds["order"] else 99),
    )
    node_count = len(ordered)

    site_payload = {
        "id": config["id"],
        "domain": config.get("domain", "academic-affairs"),
        "name": site["name"],
        "title": site["title"],
        "brand": site["brand"],
        "agentName": site["agentName"],
        "agentTagline": site["agentTagline"],
        "credit": site["credit"],
        "hello": site["hello"],
        "inputPlaceholder": site["inputPlaceholder"],
        "office": office,
        "qa": {
            "bounds": [108.0, 34.0, 109.6, 34.9],
            "examples": qa.get("examples", []),
        },
        "kinds": kinds,
        "stats": {
            "nodes": node_count,
            "days": 0,
            "points": 0,
            "photos": 0,
        },
    }

    graph_payload = {"nodes": ordered}
    days_payload = []
    map_payload = {
        "bounds": [108.0, 34.0, 109.6, 34.9],
        "layers": {
            "boundary": [], "water": [], "rivers": [], "roads": [],
            "geology": [], "soil": [], "vegetation": [], "faults": [],
            "folds": [], "attitude": [], "peaks": [], "pois": [], "places": [],
        },
    }
    photos_payload = {}

    for name, payload in {
        "site_data.json": site_payload,
        "graph_data.json": graph_payload,
        "days_data.json": days_payload,
        "map_data.json": map_payload,
        "photos_index.json": photos_payload,
    }.items():
        target = data_dir / name
        target.write_text(
            json.dumps(payload, ensure_ascii=False, separators=(",", ":")),
            encoding="utf-8",
        )
        print(f"  {target.name}: {len(json.dumps(payload, ensure_ascii=False))} 字节")

    print(f"已生成西北大学教务示例知识库：{node_count} 个基础节点，来源日期 2026-09。")


def main() -> int:
    cfg_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_CONFIG
    config = load_config(cfg_path)
    build(config)
